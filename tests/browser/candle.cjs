// The candle helper: ONE press on it picks it up and it follows the pointer while dragging
// (mouse, and a finger with MOBILE=landscape); a second click puts it down.
const { launch, player, enter, check } = require('./lib.cjs')
;(async () => {
  const { browser, page, errs } = await launch()
  await player(page, { name: 'Candle' })
  await enter(page)
  await page.waitForSelector('.candle-tool', { timeout: 60000 })
  await page.waitForTimeout(800)
  const torch = () => page.evaluate(() => { const v = window.__hall.hall.uTorch.value; const d = document.querySelector('.torch-cursor'); return { on: !!d, at: d ? d.style.transform : '', k: +v.w.toFixed(2) } })
  const b = await page.$eval('.candle-tool', e => { const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  if (process.env.MOBILE) {
    const cdp = await page.context().newCDPSession(page)
    const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
    await touch('touchStart', b.x, b.y)
    for (let k = 1; k <= 12; k++) await touch('touchMove', b.x + k * 25, b.y + k * 12)
    await page.waitForTimeout(300)
    const t = await torch()
    check(t.on && Math.abs(parseFloat(t.at.slice(10)) - (b.x + 316)) < 2, `one touch picks it up and the drag carries it: ${t.at}, light ${t.k}`)
    await touch('touchEnd', 0, 0)
    await page.waitForTimeout(300)
    check((await torch()).on, 'it stays lit after lifting the finger')
  } else {
    await page.mouse.move(b.x, b.y)
    await page.mouse.down()
    await page.waitForTimeout(100)
    check((await torch()).on, 'one press picks the candle up')
    for (let k = 1; k <= 10; k++) await page.mouse.move(b.x + k * 40, b.y + k * 25)
    await page.waitForTimeout(350)
    const t = await torch()
    check(Math.abs(parseFloat(t.at.slice(10)) - (b.x + 416)) < 2 && t.k > 0.5, `dragging carries it: ${t.at}, light ${t.k}`)
    await page.mouse.up()
    await page.waitForTimeout(300)
    check((await torch()).on, 'still carried after letting go (it was not put down)')
    await page.mouse.move(700, 450); await page.waitForTimeout(200)
    check((await torch()).at.includes('716px'), 'and it keeps following the mouse')
    await page.click('.candle-tool')
    await page.waitForTimeout(300)
    check(!(await torch()).on, 'one more click puts it down')

    // zoomed in on a portrait and on the clock, the candle can still be picked up and lights the room
    for (const target of [{ kind: 'portrait', index: 0 }, { kind: 'clock' }]) {
      const name = target.kind
      const a = await page.evaluate(t => window.__hall.anchor(t), target)
      await page.mouse.click(a.x, a.y + 40)
      await page.waitForSelector('.note-panel', { timeout: 5000 })
      await page.waitForTimeout(900)                       // the camera zooms in
      const top = await page.evaluate(() => {
        const r = document.querySelector('.candle-tool').getBoundingClientRect()
        const el = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)
        return !!el && !!el.closest('.candle-tool')
      })
      check(top, `${name} zoomed in: nothing covers the candle`)
      await page.click('.candle-tool')
      await page.mouse.move(a.x + 30, a.y + 20)
      await page.waitForTimeout(400)
      const t = await torch()
      check(t.on && t.k > 0.5, `${name} zoomed in: the candle is picked up and lights the room (light ${t.k})`)
      await page.screenshot({ path: require('./lib.cjs').T + `candle_zoom_${name}.jpg`, quality: 75 })
      await page.click('.candle-tool')
      await page.waitForTimeout(300)
      check(!(await torch()).on, `${name} zoomed in: one more click puts it down`)
      await page.click('.panel-close')
      await page.waitForTimeout(600)
    }
    // the answer panel covers the whole room: the light goes out under it
    await page.click('.candle-tool'); await page.mouse.move(700, 450); await page.waitForTimeout(300)
    check((await torch()).on, 'carried again before answering')
    await page.click('.answer-button'); await page.waitForSelector('.lock'); await page.waitForTimeout(600)
    const under = await torch()
    check(!under.on && under.k < 0.05, `under the answer panel the light is out (light ${under.k})`)
  }
  console.log(errs.join('\n') || 'no page errors')
  await browser.close()
})().catch(e => { console.error(e); process.exit(1) })
