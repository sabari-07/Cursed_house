// The witch death in a painted room (LEVEL=2|3): a wrong answer, frames at 1.6 s and 3.9 s, then where the player resumes.
const { launch, player, enter, answer, T } = require('./lib.cjs')
;(async () => {
  const LEVEL = Number(process.env.LEVEL || 2)
  const { browser, page, errs } = await launch()
  await player(page, { level: LEVEL, stage: 3, query: '?seed=11' })
  await enter(page)
  await page.waitForSelector('.question-bar', { timeout: 60000 })
  await page.waitForFunction(() => window.__hall.hallMats.death, null, { timeout: 60000 })
  await answer(page, { wrong: true })
  const t0 = Date.now()
  await page.waitForTimeout(1600)
  await page.screenshot({ path: `${T}L${LEVEL}_death1.6.jpg`, quality: 80 })
  await page.waitForTimeout(3900 - (Date.now() - t0))
  await page.screenshot({ path: `${T}L${LEVEL}_death3.9.jpg`, quality: 80 })
  await page.waitForSelector('.player-card', { timeout: 30000 })
  const f = await page.evaluate(() => JSON.parse(localStorage.getItem('ghostwriter_users_v1')).users[0].progress)
  console.log('after death:', JSON.stringify({ level: f.level, stage: f.stage, deaths: f.deaths }))
  console.log(errs.join('\n') || 'no errors')
  await browser.close()
})()
